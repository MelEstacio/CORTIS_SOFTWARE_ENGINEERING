CREATE TABLE artist (
id_artist BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
artist_name VARCHAR (100) NOT NULL,
company VARCHAR (100) NOT NULL,
country VARCHAR (50) NOT NULL
);
CREATE TABLE artist_group (
id_artist BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
members_quantity BIGINT NOT NULL,
CONSTRAINT fk_id_artist
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist) 
);
CREATE TABLE artist_members (
id_artista BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
artistic_name VARCHAR (100) NOT NULL,
birth_date DATE NOT NULL,
member_nationality VARCHAR (100) NOT NULL,
CONSTRAINT fk_id_artist
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist)
);
CREATE TABLE debut (
id_debut BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
debut_date DATE NOT NULL,
debut_type VARCHAR(30) NOT NULL,
id_artist BIGINT NOT NULL,
CONSTRAINT fk_id_artist
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist)
);
CREATE TABLE products (
id_products BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
product_name VARCHAR(120) NOT NULL,
product_price NUMERIC(10,2) NOT NULL,
product_category VARCHAR (50) NOT NULL,
inventory INT NOT NULL,
id_artist INT NOT NULL,
CONSTRAINT fk_id_artist
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist)
);
CREATE TABLE order_info (
id_order BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
date_order DATE NOT NULL,
status_order VARCHAR (50) NOT NULL,
subtotal NUMERIC (10,2) NOT NULL,
total_valeu NUMERIC (10,2) NOT NULL,
shipping_fee NUMERIC (10,2) NOT NULL,
shipping_method VARCHAR (50) NOT NULL,
id_user BIGINT (100) NOT NULL,
CONSTRAINT fk_id_fan
	FOREIGN KEY (id_fan)
	REFERENCES fan(id_fan)
);
CREATE TABLE order_item (
id_order_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
order_quantity INT NOT NULL,
unity_price NUMERIC (10,2) NOT NULL,
id_order BIGINT NOT NULL,
CONSTRAINT fk_id_order 
	FOREIGN KEY (id_order)
	REFERENCES order_info(id_order),
id_products BIGINT NOT NULL,
CONSTRAINT fk_id_products
	FOREIGN KEY (id_products)
	REFERENCES products(id_products)
);




