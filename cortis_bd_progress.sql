CREATE TABLE artist (
id_artist BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
artist_name VARCHAR (100) NOT NULL,
company VARCHAR (100) NOT NULL,
country VARCHAR (50) NOT NULL
);
CREATE TABLE artist_group (
members_quantity BIGINT NOT NULL,
id_artist BIGINT PRIMARY KEY,
CONSTRAINT fk_id_artist_group
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist) 
);
CREATE TABLE artist_members (
artistic_name VARCHAR (100) NOT NULL,
birth_date DATE NOT NULL,
member_nationality VARCHAR (100) NOT NULL,
id_artist BIGINT PRIMARY KEY,
CONSTRAINT fk_id_artist_members
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist)
);
CREATE TABLE debut (
id_debut BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
debut_date DATE NOT NULL,
debut_type VARCHAR(30) NOT NULL,
id_artist BIGINT NOT NULL,
CONSTRAINT fk_id_artist_debut
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist)
);
CREATE TABLE products (
id_products BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
product_name VARCHAR(120) NOT NULL,
product_price NUMERIC(10,2) NOT NULL,
product_category VARCHAR (50) NOT NULL,
inventory INT NOT NULL,
id_artist BIGINT NOT NULL,
CONSTRAINT fk_id_artist_products
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist)
);
CREATE TABLE loyalty_level (
id_level BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name_level VARCHAR (100) NOT NULL,
description_level VARCHAR (150) NOT NULL,
minimum_points INT NOT NULL,
CONSTRAINT chk_minimum_points
    CHECK (minimum_points >= 0)
);
CREATE TABLE fan (
id_fan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
fan_name VARCHAR (150) NOT NULL,
fan_email VARCHAR (100) NOT NULL,
password_hash VARCHAR(255) NOT NULL,
birth_date DATE NOT NULL,
account_creation_at TIMESTAMP NOT NULL,
id_level BIGINT NOT NULL,
CONSTRAINT fk_level_fan
	FOREIGN KEY (id_level)
	REFERENCES loyalty_level(id_level),
current_points INT NOT NULL,
CONSTRAINT chk_fan_points
    CHECK (current_points >= 0)
);
CREATE TABLE orders (
id_order BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
order_date TIMESTAMP NOT NULL,
total_value NUMERIC (10,2) NOT NULL,
shipping_fee NUMERIC (10,2) NOT NULL,
id_fan BIGINT NOT NULL,
CONSTRAINT fk_fan_order
	FOREIGN KEY (id_fan)
	REFERENCES fan(id_fan)
status VARCHAR (30) NOT NULL,
CONSTRAINT chk_status
    CHECK (status IN (
        'pending',
        'paid',
        'processing',
        'shipped',
        'delivered',
        'cancelled'
    )),
shipping_method VARCHAR (30) NOT NULL,
CONSTRAINT chk_shipping_method
	CHECK (shipping_method IN(
		'standard',
		'express',
		'economy',
		'same day',
		'pickup'
	))
);
CREATE TABLE order_items (
id_order_item BIGINT GENERATED BY DEFAULT AS PRIMARY KEY,
unity_price NUMERIC (10,2) NOT NULL,
item_quantity INT NOT NULL,
CONSTRAINT chk_item_quantity
	CHECK (item_quantity > 0),
id_order BIGINT NOT NULL,
CONSTRAINT fk_id_order
	FOREIGN KEY (id_order)
	REFERENCES orders(id_order)
id_products BIGINT NOT NULL,
CONSTRAINT fk_id_products_items
	FOREIGN KEY (id_products)
	REFERENCES products(id_products)
);
CREATE TABLE payment_method (
id_paymethod BIGINT GENERATED BY DEFAULT AS PRIMARY KEY,
type_paymethod VARCHAR (30) NOT NULL,
CONSTRAINT chk_type_method
	CHECK (type_method IN(
		'credit_card',
		'debit_card',
		'pix',
		'bank_transfer'
	)),
id_fan BIGINT NOT NULL,
CONSTRAINT fk_id_fan_payment
	FOREIGN KEY (id_fan)
	REFERENCES fan(id_fan)
);
CREATE TABLE events (
id_events BIGINT GENERATED BY DEFAULT AS PRIMARY KEY,
event_name VARCHAR (60) NOT NULL,
event_description VARCHAR (120) NOT NULL, 
start_date TIMESTAMP NOT NULL,
end_date TIMESTAMP NOT NULL, 
place VARCHAR (100) NOT NULL, 
event_type VARCHAR (60) NOT NULL,
CONSTRAINT chk_event_type
    CHECK (event_type IN (
        'concert',
        'festival',
        'fan_meeting',
        'album_release',
        'live_stream',
        'fan_sign',
        'showcase',
        'pop_up_event'
    )),
id_artist BIGINT NOT NULL,
CONSTRAINT fk_id_artist_events
	FOREIGN KEY (id_artist)
	REFERENCES artist(id_artist),
);
